import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const pkg = JSON.parse(read('package.json'));
assert.match(pkg.version, /^3\.\d+\.\d+$/);
assert.equal(JSON.parse(read('package-lock.json')).version, pkg.version);
const factory = read('src/repositories/repositoryFactory.ts');
assert.match(factory, /isSimulatorRuntimeAllowed/);
assert.match(factory, /'unavailable'/);
assert.match(factory, /BACKEND_NOT_CONFIGURED/);
assert.match(factory, /RUNTIME_CONFIG\.isDevelopment/);
assert.match(read('src/config/runtimeConfig.ts'), /environment\.DEV === true/);
const auth = read('src/context/AuthContext.tsx');
assert.match(auth, /Password sign-in is unavailable in simulator mode/);
assert.match(auth, /if \(!isDev \|\| isSupabaseConfigured\) return \{ success: false, error: 'Demo persona login is available only in development builds without a configured production backend\.'/);
const assets = read('src/services/assetService.ts');
assert.match(assets, /isSupabaseConfigured\) && active/);
assert.match(assets, /assetCatalogRepository\.loadAll\(\)/);
assert.doesNotMatch(assets, /supabase\.from\(/);
const faultRepo = read('src/repositories/domain/FaultCommandRepository.ts');
for (const token of ['create_fault_idempotent','transition_fault_idempotent','createMutationCommand']) assert.ok(faultRepo.includes(token));
const reliability = read('src/services/reliabilityService.ts');
assert.match(reliability, /create_outage_idempotent/);
const handlers = read('src/lib/offlineOperationalHandlers.ts');
for (const token of ['work_order.create','work_order.transition','fault.create','fault.transition','outage.create','ptw.create','ptw.transition','inventory.issue','inventory.transaction']) assert.ok(handlers.includes(token), `Missing safe replay handler ${token}`);
const processor = read('src/lib/offlineMutationProcessor.ts');
assert.match(processor, /this\.processing/);
const migration = read('supabase/migrations/20261126_idempotent_fault_outage_operations.sql');
for (const token of ['create_fault_idempotent','transition_fault_idempotent','create_outage_idempotent','Operation id belongs to another actor','Active PowerGIS user profile required','ALTER TABLE public.faults ADD COLUMN IF NOT EXISTS updated_at','CONCURRENCY_CONFLICT','operation_id = p_operation_id']) assert.ok(migration.includes(token));
assert.match(read('src/App.tsx'), /registerOperationalOfflineHandlers\(\)/);
assert.match(read('src/components/layout/ScopeBanner.tsx'), /Production · backend unavailable/);
assert.doesNotMatch(read('src/components/layout/ScopeBanner.tsx'), /rlsActiveBadge/);
for (const file of fs.readdirSync(path.join(root, 'src/services')).filter(name => name.endsWith('.ts'))) {
  if (file === 'backendService.ts' || file === 'authService.ts') continue;
  assert.doesNotMatch(read(`src/services/${file}`), /supabase\.(from|rpc)\(/, `Direct table/RPC access must stay behind repositories: ${file}`);
}
console.log('PowerGIS 3.12 production architecture checks passed.');
