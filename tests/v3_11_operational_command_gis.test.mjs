import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const pkg = JSON.parse(read('package.json'));
assert.match(pkg.version, /^3\.\d+\.\d+$/);
const app = read('src/App.tsx');
assert.match(app, /OperationalRecordDrawer/);
const drawer = read('src/components/common/OperationalRecordDrawer.tsx');
for (const token of ['faultRepository.list()', 'workOrderRepository.list()', 'outageRepository.list()', 'ptwRepository.list()', 'Operational relationships', 'Geographic reference']) assert.ok(drawer.includes(token), `Missing GIS record integration: ${token}`);
const summary = read('src/components/dashboard/OperationalSummary.tsx');
assert.match(summary, /onNavigateTab\?\.\(target\)/);
assert.match(summary, /data\.exceptions\.dataQualityIssues/);
const quality = read('src/services/dataQualityService.ts');
for (const token of ['checkCodes(', 'feeder-orphan-substation-', 'transformer-orphan-feeder-', 'pole-orphan-transformer-', 'consumer-orphan-pole-', 'invalid-coordinate-']) assert.ok(quality.includes(token), `Missing data-quality check: ${token}`);
const migration = read('supabase/migrations/20261125_operational_event_notifications.sql');
for (const token of ['emit_operational_event_notification', 'trg_fault_operational_notification_insert', 'trg_work_order_operational_notification_update', 'trg_outage_operational_notification_insert', 'trg_safety_permit_operational_notification_update', 'user_notifications']) assert.ok(migration.includes(token), `Missing event notification: ${token}`);
assert.ok(!read('src/index.css').includes('grayscale(100%)'));
console.log('PowerGIS 3.11 operational command & GIS integration checks passed.');
