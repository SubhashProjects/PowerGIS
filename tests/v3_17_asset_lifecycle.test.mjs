import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const pkg = JSON.parse(read('package.json'));
assert.match(pkg.version, /^3\.\d+\.\d+$/);
const migration = read('supabase/migrations/20261117_asset_lifecycle_management.sql');
assert.match(migration, /CREATE TABLE IF NOT EXISTS public\.equipment_lifecycle_events/);
assert.match(migration, /ENABLE ROW LEVEL SECURITY/);
assert.match(migration, /SECURITY INVOKER/);
assert.match(migration, /record_equipment_lifecycle_assessment/);
assert.match(migration, /condition_score BETWEEN 0 AND 100/);
assert.match(read('supabase/SUPABASE_ALL_IN_ONE_MASTER.sql'), /record_equipment_lifecycle_assessment/);
assert.match(read('src/services/assetService.ts'), /validateAssetConditionScore/);
const repository = read('src/repositories/domain/AssetCatalogRepository.ts');
assert.match(repository, /saveLifecycleAssessment/);
assert.match(repository, /equipment_lifecycle_events/);
const service = read('src/services/assetService.ts');
assert.match(service, /assessLifecycle/);
assert.match(service, /registerLifecycle/);
assert.match(service, /No local-only operational update was made/);
const ui = read('src/components/assets/AssetLifecycleManagement.tsx');
for (const feature of ['Condition assessment', 'Register asset lifecycle', 'Recent assessment history', 'replacement priority']) assert.ok(ui.toLowerCase().includes(feature.toLowerCase()), `missing ${feature}`);
assert.match(read('src/App.tsx'), /activeTab === 'asset_lifecycle'/);
assert.match(read('src/config/navigationConfig.ts'), /id: 'asset_lifecycle'/);
console.log('PowerGIS 3.17 asset lifecycle static tests passed.');
