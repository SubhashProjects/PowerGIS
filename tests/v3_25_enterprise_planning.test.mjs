import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const pkg = JSON.parse(read('package.json'));
assert.equal(JSON.parse(read('package-lock.json')).version, pkg.version);
assert.equal(read('src/config/appConfig.ts').includes(`version: '${pkg.version}'`), true);
const app = read('src/App.tsx');
assert.match(app, /EnterprisePlanningCenter/);
assert.match(app, /activeTab === 'enterprise_planning'/);
assert.match(read('src/config/navigationConfig.ts'), /id: 'enterprise_planning'/);
const service = read('src/services/enterprisePlanningService.ts');
for (const feature of ['calculateStraightLineDepreciation', 'calculateReorderQuantity', 'getWorkOrderDueState', 'buildPlanningRecommendations', 'buildAssetLabelPayload']) assert.ok(service.includes(feature), `missing ${feature}`);
assert.match(service, /Residual value cannot exceed acquisition cost/);
const ui = read('src/components/assets/EnterprisePlanningCenter.tsx');
assert.match(ui, /Rule-based prioritisation/);
for (const feature of ['Explainable operational recommendations', 'Straight-line depreciation planner', 'Asset identification labels', 'Release integration coverage']) assert.ok(ui.includes(feature), `missing ${feature}`);
assert.ok(ui.includes('QR image generator'));
assert.match(ui, /No simulated records are presented as live operational records/);
console.log('PowerGIS 3.25 enterprise planning integration tests passed.');
