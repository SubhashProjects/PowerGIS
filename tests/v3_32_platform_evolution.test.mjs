assert.ok(fs.existsSync(path.join(root,'public/manifest.webmanifest')));
assert.ok(fs.existsSync(path.join(root,'public/powergis-sw.js')));
assert.ok(fs.existsSync(path.join(root,'public/icons/powergis-192.png')));
assert.ok(fs.existsSync(path.join(root,'public/icons/powergis-512.png')));
