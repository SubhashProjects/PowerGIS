import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const pkg = JSON.parse(read('package.json'));
assert.match(pkg.version, /^3\.\d+\.\d+$/);
assert.equal(JSON.parse(read('package-lock.json')).version, pkg.version);
assert.match(read('src/config/appConfig.ts'), /version: '3\.\d+\.\d+'/);
const model = read('src/services/networkModelService.ts');
for (const token of ['traceNetwork','summarizePhaseCoverage','compareNetworkSnapshots','blockedSwitchIds','unknownSwitchIds','missingPhaseDataConductorIds']) assert.ok(model.includes(token), `Missing network model capability: ${token}`);
const assets = read('src/types/assets.ts');
for (const token of ['NetworkPhase','NetworkSwitch','phases?','isEnergized?']) assert.ok(assets.includes(token), `Missing additive asset model field: ${token}`);
const ui = read('src/components/topology/NetworkTraceViewer.tsx');
for (const token of ['Phase-aware network trace','Start pole','R phase','Phase data gaps','Missing phase membership is unknown']) assert.ok(ui.includes(token), `Missing phase UI: ${token}`);
assert.match(model, /edge\.state !== 'closed'/, 'Unknown/open switches must not be traversed');
assert.match(model, /if \(phase && edge\.phases && !edge\.phases\.includes\(phase\)\)/, 'Phase trace must respect recorded phase membership');
console.log('PowerGIS 3.16 network model architecture checks passed.');
